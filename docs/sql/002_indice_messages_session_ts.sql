-- 1. "2N varreduras de messages por render" está ERRADO, e superestima.
--    O plano real, medido:
--    . no filtro padrão ("Todas"), o join lateral de contagem é ELIMINADO pelo
--      planejador: nenhuma coluna dele é usada. Ele só materializa em
